"""Generate the extension's strings, locales and icons, and package it.

    py chrome/build_extension.py          regenerate everything in chrome/
    py chrome/build_extension.py --zip    ...and pack dist-chrome/: the store
                                          zip, and the same files unpacked

One source for every word, as on the desktop: strings.js is GENERATED from
blink_i18n.py (everything the extension shares with the app) and
ext_strings.py (the few things only the extension says). Before writing a
byte it checks that every string the extension's code and pages ask for
exists in all thirty languages -- a key wrong by one character would
otherwise show English forever, and nothing else would ever notice.
"""

import io
import json
import os
import re
import shutil
import sys
import zipfile

# No __pycache__ inside chrome/: Chrome refuses to load an unpacked extension
# holding any file or folder whose name starts with an underscore.
sys.dont_write_bytecode = True

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, REPO)
sys.path.insert(0, HERE)

import blink_i18n                     # noqa: E402
import ext_strings                    # noqa: E402

DISPLAY_NAME = "Dry Eyes Blink Reminder Lite"
DESCRIPTION_MAX = 132                 # the Chrome Web Store's own limit

# Our codes as Chrome names its locales. Urdu has no Chrome locale: it is
# reached through the extension's own language picker instead.
CHROME_LOCALES = {"zh-Hant": "zh_TW", "zh-Hans": "zh_CN", "pt": "pt_BR",
                  "nb": "no", "ur": None}

# What gets packed. Everything else in chrome/ is tooling.
PACKED = ("manifest.json", "background.js", "core.js", "strings.js",
          "i18n.js", "cue.js", "dot.js", "offscreen.html", "offscreen.js",
          "popup.html", "popup.js", "options.html", "options.js",
          "ui.css", "icons", "_locales")

T_CALL = re.compile(r'\bT\(\s*"((?:[^"\\]|\\.)*)"')
DATA_T = re.compile(r'data-t="([^"]*)"')


def used_keys():
    """Every string the extension asks for, read out of its own files."""
    keys = set()
    for name in sorted(os.listdir(HERE)):
        path = os.path.join(HERE, name)
        if name.endswith(".js") and name != "strings.js":
            with io.open(path, encoding="utf-8") as fh:
                keys.update(json.loads('"%s"' % m) for m in T_CALL.findall(fh.read()))
        elif name.endswith(".html"):
            with io.open(path, encoding="utf-8") as fh:
                keys.update(DATA_T.findall(fh.read()))
    return keys


def tables(keys):
    """{code: {english: translation}} for the keys asked for, or exit."""
    ext = {code: dict(zip(ext_strings.KEYS, vals))
           for code, vals in ext_strings.STRINGS.items()}
    codes = [c for _label, c in blink_i18n.LANGUAGES if c != "en"]
    problems, out = [], {}
    for code in codes:
        shared = blink_i18n.STRINGS.get(code, {})
        own = ext.get(code, {})
        table = {}
        for key in sorted(keys):
            value = own.get(key, shared.get(key))
            if value is None:
                problems.append("%s: %r" % (code, key))
            else:
                table[key] = value
        out[code] = table
    if problems:
        sys.exit("missing translations:\n  " + "\n  ".join(problems))
    return out


def write_strings(keys, out):
    payload = {
        "LANGUAGES": [list(p) for p in blink_i18n.LANGUAGES],
        "RTL": sorted(blink_i18n.RTL_LANGUAGES),
        "STRINGS": out,
    }
    with io.open(os.path.join(HERE, "strings.js"), "w", encoding="utf-8",
                 newline="\n") as fh:
        fh.write("// GENERATED by build_extension.py from blink_i18n.py and "
                 "ext_strings.py.\n// Do not edit: change those and rebuild.\n\n")
        fh.write("export const LANGUAGES = [\n%s\n];\n\n" % ",\n".join(
            "  " + json.dumps(p, ensure_ascii=False) for p in payload["LANGUAGES"]))
        fh.write("export const RTL = %s;\n\n" % json.dumps(payload["RTL"]))
        fh.write("export const STRINGS = %s;\n" % json.dumps(
            payload["STRINGS"], ensure_ascii=False, indent=1, sort_keys=True))
    print("strings.js: %d strings x %d languages" % (len(keys), len(out) + 1))


def write_locales():
    descriptions = {"en": ext_strings.ENGLISH_DESCRIPTION}
    i = ext_strings.KEYS.index("extDescription")
    for code, vals in ext_strings.STRINGS.items():
        descriptions[code] = vals[i]
    written = 0
    for code, text in descriptions.items():
        locale = CHROME_LOCALES.get(code, code)
        if locale is None:
            continue
        if len(text) > DESCRIPTION_MAX:
            sys.exit("%s description is %d characters, max %d"
                     % (code, len(text), DESCRIPTION_MAX))
        folder = os.path.join(HERE, "_locales", locale)
        os.makedirs(folder, exist_ok=True)
        with io.open(os.path.join(folder, "messages.json"), "w",
                     encoding="utf-8", newline="\n") as fh:
            json.dump({"extName": {"message": DISPLAY_NAME},
                       "extDescription": {"message": text}},
                      fh, ensure_ascii=False, indent=2)
            fh.write("\n")
        written += 1
    print("_locales: %d" % written)


def write_icons():
    """The desktop app's own mark, from its own drawing code -- plus a grey
    one for the toolbar while reminders are off or snoozed."""
    import blink_reminder
    from PIL import Image
    folder = os.path.join(HERE, "icons")
    os.makedirs(folder, exist_ok=True)
    for size in (16, 32, 48, 128):
        img = blink_reminder.app_icon(size)
        img.save(os.path.join(folder, "icon-%d.png" % size))
        if size in (16, 32):
            grey = img.convert("LA").convert("RGBA")
            alpha = grey.getchannel("A").point(lambda a: int(a * 0.55))
            grey.putalpha(alpha)
            grey.save(os.path.join(folder, "icon-off-%d.png" % size))
    print("icons: 4 sizes, plus the grey toolbar pair")


def pack():
    with io.open(os.path.join(HERE, "manifest.json"), encoding="utf-8") as fh:
        version = json.load(fh)["version"]
    out_dir = os.path.join(REPO, "dist-chrome")
    os.makedirs(out_dir, exist_ok=True)
    target = os.path.join(out_dir, "blink-reminder-chrome-%s.zip" % version)
    unpacked = os.path.join(out_dir, "unpacked")
    shutil.rmtree(unpacked, ignore_errors=True)
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as z:
        for item in PACKED:
            path = os.path.join(HERE, item)
            if os.path.isdir(path):
                shutil.copytree(path, os.path.join(unpacked, item))
                for base, _dirs, files in os.walk(path):
                    for f in sorted(files):
                        full = os.path.join(base, f)
                        z.write(full, os.path.relpath(full, HERE).replace("\\", "/"))
            else:
                os.makedirs(unpacked, exist_ok=True)
                shutil.copy2(path, os.path.join(unpacked, item))
                z.write(path, item)
    print("packed: %s (%.0f KB)" % (target, os.path.getsize(target) / 1024.0))
    print("unpacked, for chrome://extensions > Load unpacked: %s" % unpacked)


if __name__ == "__main__":
    keys = used_keys()
    write_strings(keys, tables(keys))
    write_locales()
    write_icons()
    if "--zip" in sys.argv:
        pack()
